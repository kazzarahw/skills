#!/usr/bin/env python3
"""Step 1 scope-note scaffolder for the osint skill.

The skill tells the agent to write down five things before searching, and eleven
reference files repeat that instruction — so it gets done eleven different ways.
This script makes it one artefact every time.

Writes `scope.md` into a case directory and prints the identical text to stdout.
Any field left empty is emitted as `— NOT STATED —` so the gap is visible in the
file rather than silently absent.

Standard library only, Python 3.8+.

Usage:
    scope_note.py --objective "Confirm the operator behind the phishing domain" \\
        --subject "Acme Ltd, registrar listed 2024-11-03" \\
        --in-bounds "Passive DNS, CT logs, archived pages" \\
        --out-of-bounds "No contact, no login, no port scanning" \\
        --jurisdiction "UK and US" \\
        --case cases/acme-phish

Refuses to run without --objective and exits 2. That is the one hard stop in the
skill: an investigation with no objective is not authorised work.
"""

import argparse
import sys


class _Parser(argparse.ArgumentParser):
    """argparse exits 2 on a bad flag, which would collide with "a gate refused".

    Keeping usage errors at 1 is what makes exit 2 mean exactly one thing: the script looked at
    your data and declined. An agent that cannot tell a mistyped flag from a detected credential
    will eventually report one as the other.
    """

    def error(self, message):
        self.print_usage(sys.stderr)
        print(f"{self.prog}: error: {message}", file=sys.stderr)
        raise SystemExit(1)

from pathlib import Path

NOT_STATED = "— NOT STATED —"

INTERACTIVE_GLOSS = {
    "yes": (
        "permitted — account creation, contact, and any authenticated request to a "
        "subject-controlled system stay in bounds only where named above"
    ),
    "no": (
        "refused — passive collection only. No account creation, no contact, no "
        "authenticated request to any subject-controlled system"
    ),
    "unknown": NOT_STATED,
}

TEMPLATE = """# Scope Note

_Generated by `scripts/scope_note.py`. Replace every `{not_stated}` before you collect._

## Subject

{subject}

Distinguish this from anyone with a similar name. Write the discriminators you will
filter every candidate on, and reject a candidate that fails either list.

- Must have:
- Must not have:

## Objective

{objective}

- **Decision this feeds**: {decision}
- **What would settle it**: {settle}

## In bounds

{in_bounds}

**Interactive probing**: {interactive}

## Out of bounds

{out_of_bounds}

## Jurisdiction

{jurisdiction}

## Out of bounds in one line

Name the single action that would put this investigation out of bounds, in one line.
If you cannot write it, you have not bounded the investigation.

>
"""


def field(value):
    """Normalise a flag into one template line, or mark it not stated."""
    if value is None:
        return NOT_STATED
    collapsed = " ".join(part.strip() for part in value.split() if part.strip())
    return collapsed if collapsed else NOT_STATED


def render(args):
    """Build the scope note. Every gap is visible, none is omitted."""
    interactive = INTERACTIVE_GLOSS[args.interactive_probing]
    return TEMPLATE.format(
        not_stated=NOT_STATED,
        subject=field(args.subject),
        objective=field(args.objective),
        decision=field(args.decision),
        settle=field(args.settle),
        in_bounds=field(args.in_bounds),
        interactive=interactive,
        out_of_bounds=field(args.out_of_bounds),
        jurisdiction=field(args.jurisdiction),
    )


def build_parser():
    parser = _Parser(
        epilog="Exit codes: 0 success | 1 usage error | 2 no objective supplied, or the case path is unwritable | 3 environment error.",
        prog="scope_note.py",
        description="Write the Step 1 scope note (subject, objective, bounds, jurisdiction) "
                    "to <case>/scope.md.",
    )
    parser.add_argument("--subject", help="the specific entity, plus the discriminators you will use")
    parser.add_argument("--objective", help="one sentence: the decision this investigation feeds")
    parser.add_argument("--in-bounds", dest="in_bounds", help="selector types, sources, whether interaction is allowed")
    parser.add_argument("--out-of-bounds", dest="out_of_bounds", help="named things you will not do")
    parser.add_argument("--jurisdiction", help="whose law governs you, the subject, and the data")
    parser.add_argument("--decision", help="the decision this feeds, for the objective sub-field")
    parser.add_argument("--settle", help="the condition that would settle the objective")
    parser.add_argument("--case", default=".", metavar="DIR",
                        help="case directory to write scope.md into (created if needed; default: cwd)")
    parser.add_argument("--interactive-probing", dest="interactive_probing",
                        choices=("yes", "no", "unknown"), default="unknown",
                        help="boundary decision for the email and domain workflows (default: unknown)")
    return parser


def main(argv=None):
    args = build_parser().parse_args(argv)

    # The one hard stop. Missing, empty, and whitespace-only all collapse to
    # NOT_STATED, so all three are refused the same way.
    if field(args.objective) == NOT_STATED:
        print(
            "scope_note.py: refusing to write a scope note with no objective.\n"
            "  An investigation with no decision it feeds is not authorised work.\n"
            "  State the decision this feeds, or stop the investigation.",
            file=sys.stderr,
        )
        return 2

    case_dir = Path(args.case).expanduser()
    try:
        case_dir.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        print("scope_note.py: cannot create case directory {}: {}".format(case_dir, exc), file=sys.stderr)
        return 2

    target = case_dir / "scope.md"
    content = render(args)

    if target.exists():
        print("scope_note.py: overwriting existing {}".format(target), file=sys.stderr)

    try:
        target.write_text(content, encoding="utf-8")
    except OSError as exc:
        print("scope_note.py: cannot write {}: {}".format(target, exc), file=sys.stderr)
        return 2

    sys.stdout.write(content)
    print("scope_note.py: wrote {}".format(target), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
