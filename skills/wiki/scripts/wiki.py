def parse_frontmatter(text):
    """Split a page into (fields, body, error).

    fields maps a key to either a string (scalar) or a list of strings (block
    list or inline `[a, b]`). The parser is deliberately tiny and strict: it
    accepts exactly the shape `wiki.py add` writes and nothing richer.
    """
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, None, "missing frontmatter block: file does not open with '---'"
    end = -1
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end < 0:
        return None, None, "unterminated frontmatter block: no closing '---'"
    fields = {}
    current = None
    for offset, raw in enumerate(lines[1:end], start=2):
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("- "):
            if current is None or not isinstance(fields.get(current), list):
                return None, None, "line %d: list item outside a list field" % offset
            fields[current].append(unquote(stripped[2:].strip()))
            continue
        if ":" not in stripped:
            return None, None, "line %d: not a 'field: value' pair" % offset
        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip()
        if key in fields:
            return None, None, "duplicate field: %s" % key
        if value == "":
            fields[key] = []
            current = key
        elif value.startswith("[") and value.endswith("]"):
            fields[key] = [
                unquote(item.strip()) for item in value[1:-1].split(",") if item.strip()
            ]
            current = key
        else:
            fields[key] = unquote(value)
            current = None
    body = "\n".join(lines[end + 1 :]).lstrip("\n")
    return fields, body, None


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def quote(value):
    text = str(value)
    if text == "":
        return '""'
    if re.search(r"""[:#\[\]{}"']""", text) or text != text.strip():
        return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')
    return text


def render_frontmatter(fields):
    """Serialise the nine fields in canonical order."""
    out = ["---"]
    for key in FIELD_ORDER:
        value = fields.get(key, "")
        if key in LIST_FIELDS:
            items = value if isinstance(value, list) else [value]
            items = [item for item in items if item not in ("", None)]
            out.append("%s:" % key)
            for item in items:
                out.append("  - %s" % quote(item))
        else:
            # Scalars stay scalars. `lint` requires a single value here, and a one-item
            # list for a string also breaks every other YAML reader that reads these pages.
            out.append("%s: %s" % (key, quote(value) if value not in ("", None) else '""'))
    out.append("---")
    return "\n".join(out)


def render_page(fields, body):
    text = render_frontmatter(fields)
    body = (body or "").strip("\n")
    return text + "\n\n" + body + "\n" if body else text + "\n"


def parse_date(value):
    if not isinstance(value, str) or not value:
        return None
    try:
        return datetime.datetime.strptime(value.strip(), "%Y-%m-%d").date()
    except ValueError:
        return None


def today_iso():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")


def kebab(text):
    return re.sub(r"-+", "-", re.sub(r"[^0-9a-z]+", "-", text.strip().lower())).strip("-")


