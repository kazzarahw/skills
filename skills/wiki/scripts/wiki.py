#!/usr/bin/env python3
"""llm-wiki engine for the wiki skill.

Curated, provenance-tagged pages over immutable raw captures. Nine frontmatter
fields, links that resolve by title, a generated index, an append-only log and
a linter whose exit code is the finding count. Standard library only, no
network, Python 3.9+.

    python3 scripts/wiki.py init   --wiki ./.wiki
    python3 scripts/wiki.py add    --wiki ./.wiki --type entity \
        --title "Deploy Checklist" --source notes/deploy-2026-10-01.md
    python3 scripts/wiki.py search --wiki ./.wiki --query deploy
    python3 scripts/wiki.py lint   --wiki ./.wiki
"""

