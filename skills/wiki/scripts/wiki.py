def first_heading(body):
    """First `# ` heading outside fenced code, or None when there is none."""
    in_code = False
    for raw in (body or "").split("\n"):
        if raw.strip().startswith("```"):
            in_code = not in_code
            continue
        if in_code:
            continue
        stripped = raw.strip()
        if stripped.startswith("# "):
            return " ".join(stripped[2:].split())
    return None

WIKILINK_RE = re.compile(r"\[\[([^\[\]|]+?)(?:\|[^\[\]]*?)?\]\]")
WIKILINK_STRIP_RE = re.compile(r"\[\[([^\[\]|]+?)(?:\|[^\[\]]*?)?\]\]")

