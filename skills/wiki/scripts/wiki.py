def validate_fields(fields, page_label):
    """Yield (check, severity, message) for one page's frontmatter."""
    for field in REQUIRED_FIELDS:
        if field not in fields or fields[field] == "":
            yield (
                "frontmatter",
                "critical",
                "Missing required frontmatter field: %s in %s" % (field, page_label),
            )
    for field in sorted(fields):
        if field not in FIELD_ORDER:
            yield (
                "frontmatter",
                "critical",
                "Unrecognised frontmatter field: %s in %s (valid: %s)"
                % (field, page_label, ", ".join(FIELD_ORDER)),
            )
    for field in LIST_FIELDS:
        if field in fields and not isinstance(fields[field], list):
            yield (
                "frontmatter",
                "critical",
                "Field %s must be a list: %s in %s" % (field, fields[field], page_label),
            )
    for field in ("title", "type", "created", "updated", "confidence", "provenance", "status"):
        if field in fields and not isinstance(fields[field], str):
            yield (
                "frontmatter",
                "critical",
                "Field %s must be a single value, not a list: %s" % (field, page_label),
            )
    sources = fields.get("sources")
    if isinstance(sources, list) and not sources:
        yield (
            "frontmatter",
            "critical",
            "Field sources needs at least one entry: %s in %s" % ("[]", page_label),
        )
    title = fields.get("title")
    if isinstance(title, str):
        for char in TITLE_UNSAFE_CHARS:
            if char in title:
                yield (
                    "frontmatter",
                    "critical",
                    "Title contains the link-breaking character %r: %s in %s"
                    % (char, title, page_label),
                )
    for field in ("created", "updated"):
        if field in fields and fields[field] not in ("", None):
            if not isinstance(fields[field], str) or parse_date(fields[field]) is None:
                yield (
                    "frontmatter",
                    "critical",
                    "Invalid date for %s: %s in %s (expected YYYY-MM-DD)"
                    % (field, fields[field], page_label),
                )
    for field, valid in ENUM_FIELDS.items():
        value = fields.get(field)
        if value in ("", None) or not isinstance(value, str):
            continue
        if value not in valid:
            yield (
                "enum",
                "critical",
                'Invalid %s value: "%s" in %s (valid: %s)'
                % (field, value, page_label, ", ".join(valid)),
            )


def check_placement(page, out):
    """Filename prefix and directory must agree with the declared type."""
    stem = os.path.basename(page.rel)[:-3]
    declared = page.ptype
    if declared not in TYPE_DIRS:
        return
    prefix = stem.split("-", 1)[0]
    if prefix != declared:
        out.append(
            (
                "filename-type-mismatch",
                "critical",
                'Filename/type mismatch: %s declares type "%s" but its name begins with "%s-"'
                % (os.path.basename(page.rel), declared, prefix),
                page.rel,
            )
        )
    parent = os.path.basename(os.path.dirname(page.rel))
    if parent != TYPE_DIRS[declared]:
        out.append(
            (
                "filename-type-mismatch",
                "critical",
                'Wrong directory for type: %s declares type "%s" and belongs in %s/'
                % (page.rel, declared, TYPE_DIRS[declared]),
                page.rel,
            )
        )


