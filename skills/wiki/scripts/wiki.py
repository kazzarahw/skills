def cmd_init(args):
    wiki = resolve_wiki(args)
    created, existing = [], []
    for name in ("raw",) + tuple(TYPE_DIRS[t] for t in PAGE_TYPES):
        path = os.path.join(wiki, name)
        if os.path.isdir(path):
            existing.append(name + "/")
            continue
        try:
            os.makedirs(path)
        except OSError as exc:
            raise WikiError("cannot create %s: %s" % (path, exc.strerror), 3)
        created.append(name + "/")
    for name, text in ((SCHEMA_NAME, SCHEMA_MD), (INDEX_NAME, render_index_text([]))):
        path = os.path.join(wiki, name)
        if os.path.exists(path) and not args.force:
            existing.append(name)
            continue
        if args.dry_run:
            created.append(name + " (dry-run, not written)")
            continue
        try:
            write_if_changed(path, text, force=True)
        except OSError as exc:
            raise WikiError("cannot write %s: %s" % (path, exc.strerror), 3)
        created.append(name)
    log_path = os.path.join(wiki, LOG_NAME)
    if not os.path.exists(log_path):
        if args.dry_run:
            created.append(LOG_NAME + " (dry-run, not written)")
        else:
            try:
                write_if_changed(log_path, "", force=True)
            except OSError as exc:
                raise WikiError("cannot write %s: %s" % (log_path, exc.strerror), 3)
            created.append(LOG_NAME)
    else:
        existing.append(LOG_NAME)
    if args.dry_run:
        print("dry-run: would create %d item(s) under %s" % (len(created), wiki))
    else:
        print("wiki ready: %s (%d created, %d already present)" % (wiki, len(created), len(existing)))
    for name in created:
        print("  created  %s" % name)
    for name in existing:
        print("  present  %s" % name)
    return 0


def parse_title_list(values):
    out = []
    for value in values or []:
        out.extend(part.strip() for part in str(value).split(",") if part.strip())
    return out


def cmd_add(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    title = " ".join(args.title.split())
    sources = parse_title_list(args.source)
    tags = parse_title_list(args.tag)
    confidence = args.confidence or "unverified"
    provenance = args.provenance or "asserted"
    status = args.status or "active"

    if not title:
        raise WikiError("--title must not be empty", 1)
    if not sources:
        raise WikiError("--source is required at least once (a path or URL per claim's basis)", 1)
    if args.type not in PAGE_TYPES:
        raise WikiError(
            'invalid --type "%s" (valid: %s)' % (args.type, ", ".join(PAGE_TYPES)), 2
        )
    for field, value, valid in (
        ("confidence", confidence, CONFIDENCE_VALUES),
        ("provenance", provenance, PROVENANCE_VALUES),
        ("status", status, STATUS_VALUES),
    ):
        if value not in valid:
            raise WikiError(
                'invalid --%s "%s" (valid: %s)' % (field, value, ", ".join(valid)), 2
            )
    for char in TITLE_UNSAFE_CHARS:
        if char in title:
            raise WikiError(
                'title contains the link-breaking character "%s"' % char, 2
            )

    if args.filename:
        stem = args.filename[:-3] if args.filename.endswith(".md") else args.filename
    else:
        slug = kebab(title)
        if not slug:
            raise WikiError(
                'title "%s" produces an empty filename; pass --filename explicitly' % title, 2
            )
        stem = "%s-%s" % (args.type, slug)
    if "/" in stem or "\\" in stem or stem in ("", ".", ".."):
        raise WikiError('invalid --filename "%s": use a bare name inside the type directory' % stem, 1)
    prefix = stem.split("-", 1)[0]
    if prefix != args.type:
        raise WikiError(
            'filename "%s.md" starts with "%s-" but --type is "%s"; the prefix must match '
            "(see SCHEMA.md)" % (stem, prefix, args.type),
            2,
        )

    pages = load_pages(wiki)
    titles = find_titles(pages)

    stamp = today_iso()
    fields = {
        "title": title,
        "type": args.type,
        "sources": sources,
        "created": stamp,
        "updated": stamp,
        "confidence": confidence,
        "provenance": provenance,
        "status": status,
        "tags": tags,
    }
    body = ""
    if args.summary:
        body = "## Summary\n\n%s" % args.summary.strip()
    if args.body_file == "-":
        body_text = sys.stdin.read()
        body = (body + "\n\n" + body_text.strip()) if body else body_text.strip()
    elif args.body_file:
        path = os.path.expanduser(args.body_file)
        try:
            with open(path, "r", encoding="utf-8") as handle:
                body_text = handle.read()
        except OSError as exc:
            raise WikiError("cannot read --body-file %s: %s" % (path, exc.strerror), 3)
        body = (body + "\n\n" + body_text.strip()) if body else body_text.strip()

    path = os.path.join(wiki, TYPE_DIRS[args.type], stem + ".md")
    text = render_page(fields, body)
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        except OSError as exc:
            raise WikiError("cannot read %s: %s" % (path, exc.strerror), 3)
        if current == text:
            print("unchanged: %s" % os.path.relpath(path, wiki))
            return 0
        if not args.force:
            raise WikiError(
                "%s exists with different content; edit it in place or pass --force to replace it"
                % os.path.relpath(path, wiki),
                2,
            )
    clash = sorted(
        p.rel
        for existing_title, ps in titles.items()
        if existing_title.casefold() == title.casefold()
        for p in ps
        if p.path != path
    )
    if clash:
        raise WikiError('duplicate title: "%s" already used by %s' % (title, ", ".join(clash)), 2)
    if args.dry_run:
        print("dry-run: would write %s" % os.path.relpath(path, wiki))
        return 0
    try:
        write_if_changed(path, text, force=True)
    except OSError as exc:
        raise WikiError("cannot write %s: %s" % (path, exc.strerror), 3)
    print(
        "wrote %s (%d source(s), %d tag(s))"
        % (os.path.relpath(path, wiki), len(sources), len(tags))
    )
    return 0


def cmd_show(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    pages = load_pages(wiki)
    titles = find_titles(pages)
    wanted = " ".join(args.title.split())
    matches = titles.get(wanted, [])
    if not matches:
        # No exact hit: fall back to a case-insensitive match, since title case
        # is unreliable across sessions. More than one page matching means the
        # title is ambiguous and the caller must disambiguate, not guess.
        folded = wanted.casefold()
        matches = [p for t, ps in titles.items() if t.casefold() == folded for p in ps]
    if not matches:
        near = sorted(t for t in titles if wanted.lower() in t.lower())
        hint = " Nearest: %s" % ", ".join(near[:5]) if near else ""
        raise WikiError('no page titled "%s" in %s.%s' % (wanted, wiki, hint), 2)
    if len(matches) > 1:
        raise WikiError(
            'title "%s" is ambiguous: %s' % (wanted, ", ".join(sorted(p.rel for p in matches))), 2
        )
    try:
        with open(matches[0].path, "r", encoding="utf-8") as handle:
            sys.stdout.write(handle.read())
    except OSError as exc:
        raise WikiError("cannot read %s: %s" % (matches[0].rel, exc.strerror), 3)
    return 0


def score_page(page, terms):
    score = 0.0
    title = page.title.lower()
    if any(term in title for term in terms):
        score += SCORE_TITLE
    tags = [t.lower() for t in page.tags]
    score += SCORE_TAG * sum(1 for tag in tags if any(term in tag for term in terms))
    if any(term in page.body.lower() for term in terms):
        score += SCORE_CONTENT
    if page.ptype in terms:
        score += SCORE_TYPE
    if page.status in terms:
        score += SCORE_STATUS
    return score


def cmd_search(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    pages = [p for p in load_pages(wiki) if not p.error]
    if args.type and args.type not in PAGE_TYPES:
        raise WikiError(
            'invalid --type "%s" (valid: %s)' % (args.type, ", ".join(PAGE_TYPES)), 1
        )
    tags = [t.lower() for t in parse_title_list(args.tag)]
    date_from = parse_date(args.date_from) if args.date_from else None
    date_to = parse_date(args.date_to) if args.date_to else None
    if args.date_from and date_from is None:
        raise WikiError('--date-from "%s" is not YYYY-MM-DD' % args.date_from, 1)
    if args.date_to and date_to is None:
        raise WikiError('--date-to "%s" is not YYYY-MM-DD' % args.date_to, 1)
    filtering_dates = date_from is not None or date_to is not None
    if args.limit < 1:
        raise WikiError("--limit must be at least 1", 1)
    if args.offset < 0:
        raise WikiError("--offset cannot be negative", 1)

    terms = [t for t in args.query.lower().split() if t]
    excluded_missing_date = []
    scored = []
    for page in pages:
        if args.type and page.ptype != args.type:
            continue
        if args.status and page.status != args.status:
            continue
        # --tag is OR: any one matching tag qualifies the page.
        if tags and not any(tag in t.lower() for tag in tags for t in page.tags):
            continue
        if filtering_dates:
            created = page.created
            if created is None:
                # A page with no `created` fails a date filter; it is never
                # silently treated as in-window.
                excluded_missing_date.append(page.label)
                continue
            if date_from and created < date_from:
                continue
            if date_to and created > date_to:
                continue
        if terms:
            score = score_page(page, terms)
            if score <= 0:
                continue
        else:
            score = 0.0
        scored.append((score, page))
    scored.sort(key=lambda item: (-item[0], item[1].ptype, item[1].title.lower()))
    total = len(scored)
    window = scored[args.offset : args.offset + args.limit]
    rows = [
        {
            "title": page.title,
            "type": page.ptype,
            "status": page.status,
            "score": round(score, 2),
            "path": page.rel,
            "tags": page.tags,
            "created": page.fields.get("created", ""),
            "summary": page.summary,
        }
        for score, page in window
    ]
    if excluded_missing_date:
        sys.stderr.write(
            "date filter: excluded %d page(s) with no valid 'created' field: %s\n"
            % (len(excluded_missing_date), ", ".join(excluded_missing_date[:10]))
        )
    if args.json:
        json.dump(
            {
                "wiki": wiki,
                "query": args.query,
                "tags": tags,
                "type": args.type or "",
                "status": args.status or "",
                "total": total,
                "offset": args.offset,
                "limit": args.limit,
                "excluded_missing_date": excluded_missing_date,
                "results": rows,
            },
            sys.stdout,
            indent=2,
        )
        sys.stdout.write("\n")
        return 0
    if not window:
        print("no matching pages (of %d in the wiki)" % len(pages))
        return 0
    for row in rows:
        print("%6.2f  %-10s %-12s %s" % (row["score"], row["type"], row["status"], row["title"]))
        print("        %s  %s" % (row["path"], row["summary"]))
    shown = args.offset + len(window)
    print(
        "\n%d of %d match(es); showing %d-%d%s"
        % (total, len(pages), args.offset + 1, shown, "" if total <= shown else " (raise --offset)")
    )
    if excluded_missing_date:
        print(
            "excluded by the date filter for a missing 'created' field: %d page(s)"
            % len(excluded_missing_date)
        )
    return 0


def render_index_text(pages):
    """The whole of index.md: every page, grouped by type, one line each."""
    lines = [
        "# Wiki index",
        "",
        "Generated by `python3 scripts/wiki.py index --wiki <dir>`. Do not hand-edit.",
        "",
    ]
    if not pages:
        lines.extend(["No pages yet.", ""])
        return "\n".join(lines)
    titled = [p for p in pages if p.title]
    lines.append("%d page(s). Links resolve by the `title:` field." % len(titled))
    lines.append("")
    groups = []
    for ptype in PAGE_TYPES:
        groups.append((ptype.capitalize() + "s", [p for p in titled if p.ptype == ptype]))
    stray = [p for p in titled if p.ptype not in TYPE_DIRS]
    if stray:
        groups.append(("Other (type is not one of the five)", stray))
    for heading, group in groups:
        if not group:
            continue
        lines.append("## %s" % heading)
        lines.append("")
        for page in sorted(group, key=lambda p: p.title.lower()):
            suffix = "" if page.status in ("", "active") else "  (status: %s)" % page.status
            lines.append("- [[%s]] — %s%s" % (page.title, page.summary, suffix))
        lines.append("")
    return "\n".join(lines)


def cmd_index(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    pages = [p for p in load_pages(wiki) if not p.error]
    text = render_index_text(pages)
    path = os.path.join(wiki, INDEX_NAME)
    if args.dry_run:
        print("dry-run: would rewrite %s from %d page(s)" % (INDEX_NAME, len(pages)))
        return 0
    try:
        changed = write_if_changed(path, text, force=True)
    except OSError as exc:
        raise WikiError("cannot write %s: %s" % (path, exc.strerror), 3)
    print(
        "%s %s (%d page(s) in %d type(s))"
        % ("rewrote" if changed else "unchanged", INDEX_NAME, len(pages), len({p.ptype for p in pages}))
    )
    return 0


def cmd_log(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    verb = args.verb.strip()
    subject = args.subject.strip()
    if not verb or not subject:
        raise WikiError("--verb and --subject must both be non-empty", 1)
    if "\n" in verb or "\n" in subject:
        raise WikiError("--verb and --subject must each be a single line", 1)
    entry = "## [%s] %s | %s\n" % (today_iso(), verb, subject)
    path = os.path.join(wiki, LOG_NAME)
    if args.dry_run:
        print("dry-run: would append to %s: %s" % (LOG_NAME, entry.rstrip()))
        return 0
    try:
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(entry)
    except OSError as exc:
        raise WikiError("cannot append to %s: %s" % (path, exc.strerror), 3)
    print("appended: %s" % entry.rstrip())
    return 0


LINT_CHECKS = (
    ("frontmatter", "critical", "missing or unrecognised required frontmatter field"),
    ("enum", "critical", "frontmatter value outside its enumerated set"),
    ("unknown-type", "critical", "page type is not one of the five"),
    ("filename-type-mismatch", "critical", "file name or directory disagrees with the declared type"),
    ("duplicate-title", "critical", "two pages carry the same title"),
    ("title-heading", "warning", "page heading differs from its title: field"),
    ("tag-format", "warning", "tag is not lowercase kebab-case"),
    ("broken-wikilink", "critical", "wikilink target matches no page title"),
    ("invalidated-link", "critical", "body links to a page marked status: invalidated"),
    ("orphan-page", "warning", "no inbound wikilink from another page"),
    ("no-outbound-wikilink", "warning", "page links to nothing"),
    ("stale-link", "warning", "link text matches no title but matches a near-miss (likely a rename)"),
    ("index-coverage", "warning", "index.md absent or not the generated form"),
    ("unreadable-page", "info", "page could not be read or parsed"),
    ("empty-wiki", "info", "the wiki holds no pages yet"),
)

SEVERITY_RANK = {"critical": 0, "warning": 1, "info": 2}


def cmd_lint(args):
    wiki = resolve_wiki(args)
    require_wiki(wiki)
    pages = load_pages(wiki)
    good = [p for p in pages if not p.error]
    findings = []

    fix_note = "not requested"
    if args.fix:
        path = os.path.join(wiki, INDEX_NAME)
        text = render_index_text(good)
        if args.dry_run:
            fix_note = "dry-run: would rewrite index.md"
        else:
            try:
                changed = write_if_changed(path, text, force=True)
            except OSError as exc:
                raise WikiError("cannot write %s: %s" % (path, exc.strerror), 3)
            fix_note = "index.md regenerated" if changed else "index.md already current"

    titles = find_titles(good)
    lower_titles = {}
    for title, group in titles.items():
        lower_titles.setdefault(title.lower(), []).extend(group)
    stem_titles = {}
    for page in good:
        stem = os.path.basename(page.rel)[:-3]
        stem_titles.setdefault(stem.lower(), page)
        stem_titles.setdefault(stem.split("-", 1)[-1].lower(), page)
    kebab_titles = {}
    for title, group in titles.items():
        kebab_titles.setdefault(kebab(title), group)

    for page in pages:
        if page.error:
            findings.append(
                (
                    "unreadable-page",
                    "info",
                    "Unreadable page: %s (%s)" % (page.rel, page.error),
                    page.rel,
                )
            )
            continue
        label = page.label
        for finding in validate_fields(page.fields, label):
            findings.append((finding[0], finding[1], finding[2], page.rel))
        declared = page.ptype
        if declared and declared not in PAGE_TYPES:
            findings.append(
                (
                    "unknown-type",
                    "critical",
                    'Unknown page type: "%s" in %s (valid: %s)'
                    % (declared, label, ", ".join(PAGE_TYPES)),
                    page.rel,
                )
            )
        elif declared:
            check_placement(page, findings)
        if page.title:
            heading = first_heading(page.body)
            if heading is not None and heading != page.title:
                findings.append(
                    (
                        "title-heading",
                        "warning",
                        'Title/heading mismatch: title: "%s" but the heading reads "# %s" in %s'
                        % (page.title, heading, label),
                        page.rel,
                    )
                )
            for tag in page.tags:
                if not TAG_RE.match(tag):
                    findings.append(
                        (
                            "tag-format",
                            "warning",
                            'Tag "%s" is not lowercase kebab-case in %s' % (tag, label),
                            page.rel,
                        )
                    )

    by_title_dupes = {}
    for title, group in titles.items():
        if len(group) > 1:
            by_title_dupes[title] = sorted(p.rel for p in group)
            findings.append(
                (
                    "duplicate-title",
                    "critical",
                    'Duplicate title: "%s" in %s' % (title, " and ".join(sorted(p.rel for p in group))),
                    sorted(p.rel for p in group)[0],
                )
            )
    for folded, group in lower_titles.items():
        distinct = sorted(set(p.title for p in group))
        if len(distinct) > 1:
            findings.append(
                (
                    "duplicate-title",
                    "critical",
                    'Duplicate title under different case: %s in %s'
                    % (
                        ", ".join('"%s"' % t for t in distinct),
                        " and ".join(sorted(p.rel for p in group)),
                    ),
                    sorted(p.rel for p in group)[0],
                )
            )

    inbound = {p.rel: 0 for p in good}
    for page in good:
        outbound = 0
        for target in page.links():
            outbound += 1
            exact = titles.get(target)
            if exact:
                if len(exact) == 1:
                    target_page = exact[0]
                    if target_page.rel != page.rel:
                        inbound[target_page.rel] += 1
                    if target_page.status == "invalidated":
                        findings.append(
                            (
                                "invalidated-link",
                                "critical",
                                "Link to invalidated page: [[%s]] in %s" % (target, page.label),
                                page.rel,
                            )
                        )
                # More than one page carries this title: already a duplicate-title
                # critical, so the link itself is not reported as broken.
                continue
            near = lower_titles.get(target.lower()) or kebab_titles.get(kebab(target))
            if near:
                candidate = near[0]
                findings.append(
                    (
                        "stale-link",
                        "warning",
                        'Link text matches no exact title (check spelling or a rename): [[%s]] in %s '
                        '— nearest page: "%s"' % (target, page.label, candidate.title),
                        page.rel,
                    )
                )
                if candidate.rel != page.rel and len(near) == 1:
                    inbound[candidate.rel] += 1
                continue
            stem_page = stem_titles.get(target.lower())
            if stem_page:
                findings.append(
                    (
                        "stale-link",
                        "warning",
                        "Link text names a file, not a title: [[%s]] in %s — page %s carries the title "
                        '"%s"' % (target, page.label, stem_page.rel, stem_page.title),
                        page.rel,
                    )
                )
                if stem_page.rel != page.rel:
                    inbound[stem_page.rel] += 1
                continue
            findings.append(
                (
                    "broken-wikilink",
                    "critical",
                    "Broken wikilink: [[%s]] in %s" % (target, page.label),
                    page.rel,
                )
            )
        if outbound == 0:
            quiet = page.status in ("draft", "invalidated")
            findings.append(
                (
                    "no-outbound-wikilink",
                    "info" if quiet else "warning",
                    "Page has no outbound wikilink: %s" % page.label,
                    page.rel,
                )
            )

    for page in good:
        if inbound.get(page.rel, 0) == 0:
            duplicates = by_title_dupes.get(page.title)
            if duplicates and page.rel != duplicates[0]:
                continue
            quiet = page.status in ("draft", "invalidated")
            findings.append(
                (
                    "orphan-page",
                    "info" if quiet else "warning",
                    "Orphan page: %s has no inbound wikilink" % page.label,
                    page.rel,
                )
            )

    if not good:
        findings.append(("empty-wiki", "info", "No pages found under %s" % wiki, "."))
    elif not args.fix or args.dry_run:
        path = os.path.join(wiki, INDEX_NAME)
        try:
            with open(path, "r", encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current is None:
            findings.append(
                (
                    "index-coverage",
                    "warning",
                    "Index file not found: %s (run: wiki.py index --wiki <dir>)" % INDEX_NAME,
                    INDEX_NAME,
                )
            )
        elif current != render_index_text(good):
            findings.append(
                (
                    "index-coverage",
                    "warning",
                    "Index is not the generated form: %s (run: wiki.py index --wiki <dir>, or --fix)"
                    % INDEX_NAME,
                    INDEX_NAME,
                )
            )

    findings.sort(key=lambda f: (SEVERITY_RANK.get(f[1], 3), f[0], f[3], f[2]))
    counts = {"critical": 0, "warning": 0, "info": 0}
    for finding in findings:
        counts[finding[1]] = counts.get(finding[1], 0) + 1
    exit_code = 2 if counts["critical"] else (1 if counts["warning"] else 0)

    if args.json:
        json.dump(
            {
                "wiki": wiki,
                "pages": len(good),
                "unparsed": len(pages) - len(good),
                "fix": fix_note,
                "counts": counts,
                "findings": [
                    {"check": f[0], "severity": f[1], "message": f[2], "page": f[3]} for f in findings
                ],
                "exit_code": exit_code,
            },
            sys.stdout,
            indent=2,
        )
        sys.stdout.write("\n")
        return exit_code

    print("wiki: %s" % wiki)
    print("pages: %d parsed, %d unparsed; --fix: %s" % (len(good), len(pages) - len(good), fix_note))
    if not findings:
        print("clean: no findings")
        return 0
    current_check = None
    for check, severity, message, page in findings:
        if check != current_check:
            purpose = dict((c, p) for c, _s, p in LINT_CHECKS).get(check, "")
            print("\n%s [%s] — %s" % (check, severity, purpose))
            current_check = check
        print("  %-8s %s" % (severity, message))
    print(
        "\n%d critical, %d warning, %d info — exit %d"
        % (counts["critical"], counts["warning"], counts["info"], exit_code)
    )
    return exit_code


