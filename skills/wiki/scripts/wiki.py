@dataclasses.dataclass
class Page:
    rel: str
    path: str
    fields: dict
    body: str
    error: str = ""

    @property
    def title(self):
        value = self.fields.get("title", "") if self.fields else ""
        return value if isinstance(value, str) else ""

    @property
    def ptype(self):
        value = self.fields.get("type", "") if self.fields else ""
        return value if isinstance(value, str) else ""

    @property
    def status(self):
        value = self.fields.get("status", "") if self.fields else ""
        return value if isinstance(value, str) else ""

    @property
    def created(self):
        return parse_date(self.fields.get("created", "")) if self.fields else None

    @property
    def tags(self):
        value = self.fields.get("tags", []) if self.fields else []
        return [t for t in value if isinstance(t, str)] if isinstance(value, list) else []

    @property
    def sources(self):
        value = self.fields.get("sources", []) if self.fields else []
        return [s for s in value if isinstance(s, str)] if isinstance(value, list) else []

    @property
    def label(self):
        return self.title or self.rel

    @property
    def summary(self):
        return first_line_summary(self.body)

    def links(self):
        return [m.group(1).strip() for m in WIKILINK_RE.finditer(self.body)]


def first_line_summary(body, limit=110):
    """First prose line of a body, wikilink syntax and markup removed."""
    in_code = False
    for raw in (body or "").split("\n"):
        line = raw.strip()
        if line.startswith("```"):
            in_code = not in_code
            continue
        if in_code or not line:
            continue
        if line[0] in "#>|" or line.startswith("<!--") or line.startswith("---"):
            continue
        line = WIKILINK_STRIP_RE.sub(r"\1", line)
        line = re.sub(r"[*_`]+", "", line)
        line = re.sub(r"\s+", " ", line).strip(" -:")
        if not line:
            continue
        if len(line) > limit:
            line = line[: limit - 3].rstrip() + "..."
        return line
    return "no summary line"


def resolve_wiki(args):
    path = args.wiki or os.environ.get("WIKI_DIR") or DEFAULT_WIKI
    return os.path.abspath(os.path.expanduser(path))


def require_wiki(wiki):
    if not os.path.isdir(wiki):
        raise WikiError(
            "wiki not found: %s (create it with: wiki.py init --wiki %s)" % (wiki, wiki),
            3,
        )
    if not os.access(wiki, os.R_OK | os.X_OK):
        raise WikiError("wiki is not readable: %s" % wiki, 3)


def load_pages(wiki):
    """Every markdown page under the wiki, excluding raw/ and the root files."""
    pages = []
    for dirpath, dirnames, filenames in os.walk(wiki):
        dirnames[:] = sorted(d for d in dirnames if d != "raw")
        rel_dir = os.path.relpath(dirpath, wiki)
        if rel_dir == ".":
            filenames = [f for f in filenames if f.endswith(".md") and f not in RESERVED_ROOT_FILES]
        else:
            filenames = [f for f in filenames if f.endswith(".md")]
        for name in sorted(filenames):
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, wiki).replace(os.sep, "/")
            try:
                with open(path, "r", encoding="utf-8") as handle:
                    text = handle.read()
            except OSError as exc:
                pages.append(Page(rel, path, {}, "", "unreadable: %s" % exc.strerror))
                continue
            fields, body, error = parse_frontmatter(text)
            if error:
                pages.append(Page(rel, path, {}, body or "", error))
            else:
                pages.append(Page(rel, path, fields, body or "", ""))
    pages.sort(key=lambda p: (p.ptype, p.title.lower(), p.rel))
    return pages


def find_titles(pages):
    titles = {}
    for page in pages:
        if page.title and not page.error:
            titles.setdefault(page.title, []).append(page)
    return titles


def write_if_changed(path, text, force=False):
    """Write atomically. Returns True when the file changed."""
    if os.path.exists(path):
        try:
            with open(path, "r", encoding="utf-8") as handle:
                if handle.read() == text:
                    return False
        except OSError:
            pass
        if not force:
            raise WikiError(
                "%s exists with different content; pass --force to replace it"
                % os.path.relpath(path),
                2,
            )
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)
    return True


